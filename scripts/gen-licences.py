#!/usr/bin/env python3
"""Copies the licence and NOTICE files of every package the app resolves into the app.

    scripts/dev.sh python3 scripts/gen-licences.py                 # yellow: .build/checkouts
    python3 scripts/gen-licences.py --checkouts ~/ios-mosh-dd/SourcePackages/checkouts   # charlie

The list of packages is the tracked Package.resolved at the top of the repository: the app's
Xcode build resolves the same graph (MoshKit and SwiftTerm), and scripts/mac-testflight.sh
installs this file into the generated project and refuses a release whose packages differ.
For each pin the checkout must be a clean git checkout at exactly the pinned revision; its
top-level LICENSE*, LICENCE*, COPYING* and NOTICE* files are copied unchanged into
App/ThirdPartyLicences/<identity>/, and App/ThirdPartyLicences/packages.json lists them with
the version and revision. The app shows them on Settings > About > Third-party licences
(App/IOSMosh/LicencePages.swift); IOSMoshTests/LicencePagesTests fails when a pin of
Package.resolved has no licence text in the bundle.

Run it after every change to Package.resolved and commit Package.resolved and
App/ThirdPartyLicences together. It exits non-zero, and writes nothing, when a checkout is
missing, at another revision, modified, or has no licence file.
"""
import argparse
import json
import pathlib
import re
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
LICENCE_FILE = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE)([._-].*)?$", re.IGNORECASE)


def git(checkout, *args):
    return subprocess.run(["git", "-C", str(checkout), *args], check=True,
                          capture_output=True, text=True).stdout.strip()


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--checkouts", default=str(ROOT / ".build" / "checkouts"),
                        help="the build tree's package checkouts (default: .build/checkouts)")
    parser.add_argument("--resolved", default=str(ROOT / "Package.resolved"))
    parser.add_argument("--out", default=str(ROOT / "App" / "ThirdPartyLicences"))
    args = parser.parse_args()

    checkouts = pathlib.Path(args.checkouts).expanduser()
    pins = json.loads(pathlib.Path(args.resolved).read_text())["pins"]
    errors, packages, copies = [], [], []
    for pin in sorted(pins, key=lambda p: p["identity"]):
        identity, location, state = pin["identity"], pin["location"], pin["state"]
        name = location.rstrip("/").rsplit("/", 1)[-1].removesuffix(".git")
        checkout = checkouts / name
        if not checkout.is_dir():
            errors.append(f"{identity}: no checkout at {checkout}")
            continue
        head = git(checkout, "rev-parse", "HEAD")
        if head != state["revision"]:
            errors.append(f"{identity}: checkout is at {head}, Package.resolved pins {state['revision']}")
            continue
        if git(checkout, "status", "--porcelain", "--untracked-files=no"):
            errors.append(f"{identity}: checkout has local changes")
            continue
        files = sorted(p.name for p in checkout.iterdir() if p.is_file() and LICENCE_FILE.match(p.name))
        if not any(not f.upper().startswith("NOTICE") for f in files):
            errors.append(f"{identity}: no LICENSE, LICENCE or COPYING file in {checkout}")
            continue
        packages.append({"identity": identity, "name": name, "location": location,
                         "version": state.get("version", ""), "revision": state["revision"],
                         "files": files})
        copies += [(checkout / f, identity, f) for f in files]
    if errors:
        print("\n".join(errors), file=sys.stderr)
        print("nothing written", file=sys.stderr)
        return 1

    out = pathlib.Path(args.out)
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    for source, identity, file in copies:
        (out / identity).mkdir(exist_ok=True)
        shutil.copyfile(source, out / identity / file)
    manifest = {
        "about": "Generated by scripts/gen-licences.py from Package.resolved; do not edit.",
        "packages": packages,
    }
    (out / "packages.json").write_text(json.dumps(manifest, indent=2) + "\n")
    for p in packages:
        print(f"{p['name']} {p['version']} {p['revision'][:12]}: {', '.join(p['files'])}")
    print(f"{len(packages)} packages, {len(copies)} files in {out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
